"""Generate Android resources from the reviewed catalog. Run with --check in validation."""
from pathlib import Path
import json, sys
from xml.sax.saxutils import escape
ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'tools/localization.json').read_text('utf-8'))
assert len({r['key'] for r in data}) == len(data)
assert len({r['zh'] for r in data}) == len(data)
def emit(path, value):
    path = ROOT / path
    if '--check' in sys.argv:
        assert path.read_text('utf-8') == value, f'Stale generated file: {path}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(value, 'utf-8')
for language in ['en', 'zh', 'ja', 'fr', 'de']:
    folder = 'values' if language == 'en' else 'values-' + language
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/generate_localization.py -->', '<resources>']
    for row in data:
        assert row[language], (row['key'], language)
        value = escape(row[language].replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'").replace('\n', '\\n'))
        lines.append(f'    <string name="{row["key"]}" formatted="false">"{value}"</string>')
    lines.append('</resources>')
    emit(f'app/src/main/res/{folder}/strings.xml', '\n'.join(lines) + '\n')
lines=['package io.perfoverlay.app;', '', 'import android.content.Context;', 'import java.util.*;', '', '/** Generated by tools/generate_localization.py. */', 'final class TranslationResources {', '    static Map<String,String> load(Context context) {', '        Map<String,String> values = new HashMap<>();']
for row in data:
    lines.append('        values.put(' + json.dumps(row['zh'], ensure_ascii=False) + ', context.getString(R.string.' + row['key'] + '));')
lines += ['        return values;', '    }', '}', '']
emit('app/src/main/java/io/perfoverlay/app/TranslationResources.java', '\n'.join(lines))
print(f'{len(data)} messages × 5 languages verified')
